# Regenerates app/services/icons.rb from a checkout of Weather Icons.
#
#   git clone https://github.com/sylturner/weather-icons /tmp/weather-icons
#   ruby script/generate_weather_icons.rb /tmp/weather-icons
#
# The Open-Meteo code => glyph mapping is read from that fork's
# less/mappings/wi-openmeteo.less, and only the glyphs it references
# (plus "na") are pulled from svg/.

root = ARGV.fetch(0)
mapping_path = File.join(root, "less", "mappings", "wi-openmeteo.less")
abort "no Open-Meteo mapping at #{mapping_path}" unless File.exist?(mapping_path)

# .@{wi-css-prefix}-openmeteo-day-0:before { content: @day-sunny ; }
RULE = /-openmeteo-(?:(day|night)-)?(\d+):before\s*\{\s*content:\s*@([a-z0-9-]+)/

mapping = { "neutral" => {}, "day" => {}, "night" => {} }
File.foreach(mapping_path) do |line|
  next unless (m = line.match(RULE))

  mapping[m[1] || "neutral"][m[2].to_i] = m[3]
end
abort "no rules parsed from #{mapping_path}" if mapping.values.any?(&:empty?)

def inner(path)
  raw = File.read(path).sub(/<\?xml.*?\?>/m, "").gsub(/<!--.*?-->/m, "").strip
  body = raw[%r{<svg\b[^>]*>(.*)</svg>}m, 1].strip
  body.gsub(/>\s+</, "><").gsub(/\s+/, " ").strip
end

glyphs = (mapping.values.flat_map(&:values) + [ "na" ]).uniq.sort
rows = glyphs.map do |name|
  body = inner(File.join(root, "svg", "wi-#{name}.svg"))
  raise "paren in #{name}" if body.match?(/[()]/)

  %(    "#{name}" => %q(#{body}).freeze)
end

codes = mapping.map do |variant, table|
  pairs = table.sort.map { |code, name| %(      #{code} => "#{name}") }
  "    #{variant}: {\n#{pairs.join(",\n")}\n    }.freeze"
end

