  # WMO code -> icon name. Open-Meteo uses these.
  def self.for_wmo(code)
    case code.to_i
    when 0        then "clear"
    when 1, 2     then "partly"
    when 3        then "cloudy"
    when 45, 48   then "fog"
    when 51..67, 80..82 then "rain"
    when 71..77, 85, 86 then "snow"
    when 95..99   then "storm"
    else "cloudy"
    end
  end

  def self.label_for_wmo(code)
    case code.to_i
    when 0 then "Clear"
    when 1 then "Mostly clear"
    when 2 then "Partly cloudy"
    when 3 then "Overcast"
    when 45, 48 then "Fog"
    when 51..57 then "Drizzle"
    when 61..67 then "Rain"
    when 71..77 then "Snow"
    when 80..82 then "Showers"
    when 85, 86 then "Snow showers"
    when 95..99 then "Thunderstorms"
    else "—"
    end
  end
